#Requires -Version 5.1
<#
.SYNOPSIS
    Prepares a local OBS SDK layout so the plugin can be built without downloading
    the full OBS dependency bundle.

.DESCRIPTION
    Creates:
      deps/sdk/include   OBS headers (libobs) matching the requested tag
      deps/sdk/lib/libobs.lib   import library generated from the installed obs.dll
      deps/sdk/lib/obs.dll      copy of the DLL the import library points at

    The import library is generated from the *installed* OBS binary, so the plugin
    is always linked against exactly the OBS version that will load it.

.EXAMPLE
    .\tools\prepare-sdk.ps1 -ObsVersion 33.0.1
#>
[CmdletBinding()]
param(
    [string]$ObsVersion = "33.0.1",
    [string]$ObsDll = "C:\Program Files\obs-studio\bin\64bit\obs.dll",
    [string]$SdkDir
)

$ErrorActionPreference = "Stop"

if (-not $SdkDir) {
    $SdkDir = Join-Path $PSScriptRoot "..\deps\sdk"
}

function Get-VcTool {
    param([string]$Name)

    $vswhere = Join-Path ${env:ProgramFiles(x86)} "Microsoft Visual Studio\Installer\vswhere.exe"
    if (-not (Test-Path $vswhere)) {
        throw "vswhere.exe not found. Install Visual Studio 2022 with the C++ workload."
    }

    $vsPath = & $vswhere -products * -requires Microsoft.VisualStudio.Component.VC.Tools.x86.x64 -latest -property installationPath
    if (-not $vsPath) {
        throw "No Visual Studio installation with the C++ toolchain was found."
    }

    $tool = Get-ChildItem (Join-Path $vsPath "VC\Tools\MSVC") -Directory |
        Sort-Object Name -Descending |
        ForEach-Object { Join-Path $_.FullName "bin\Hostx64\x64\$Name" } |
        Where-Object { Test-Path $_ } |
        Select-Object -First 1

    if (-not $tool) {
        throw "$Name not found in '$vsPath'."
    }
    return $tool
}

$SdkDir = [System.IO.Path]::GetFullPath($SdkDir)
$includeDir = Join-Path $SdkDir "include"
$libDir = Join-Path $SdkDir "lib"
$sourceDir = Join-Path $SdkDir "obs-studio-$ObsVersion"

New-Item -ItemType Directory -Force -Path $SdkDir, $libDir | Out-Null

if (-not (Test-Path $ObsDll)) {
    throw "obs.dll not found at '$ObsDll'. Pass -ObsDll <path to your OBS obs.dll>."
}

# --- OBS headers ------------------------------------------------------------

if (-not (Test-Path (Join-Path $sourceDir "libobs\obs.h"))) {
    $zip = Join-Path $SdkDir "obs-studio-$ObsVersion.zip"
    if (-not (Test-Path $zip)) {
        $url = "https://github.com/obsproject/obs-studio/archive/refs/tags/$ObsVersion.zip"
        Write-Host "Downloading OBS $ObsVersion headers..."
        & curl.exe -L --retry 3 --fail -o $zip $url
        if ($LASTEXITCODE -ne 0) { throw "Failed to download $url" }
    }

    Write-Host "Extracting OBS headers..."
    & tar.exe -xf $zip -C $SdkDir
    if ($LASTEXITCODE -ne 0) { throw "Failed to extract $zip" }
}

Write-Host "Copying libobs headers..."
if (Test-Path $includeDir) { Remove-Item -Recurse -Force $includeDir }
Copy-Item -Recurse -Force (Join-Path $sourceDir "libobs") $includeDir

# obsconfig.h is generated by the OBS build; the plugin only needs the version
# markers and the path placeholders, which are irrelevant for a plugin.
@"
#pragma once

#define OBS_DATA_PATH "data"
#define OBS_PLUGIN_PATH "obs-plugins/64bit"
#define OBS_PLUGIN_DESTINATION "obs-plugins"

#define OBS_RELEASE_CANDIDATE 0
#define OBS_BETA 0
"@ | Set-Content -Encoding ascii (Join-Path $includeDir "obsconfig.h")

# --- Import library ---------------------------------------------------------

$dumpbin = Get-VcTool "dumpbin.exe"
$libTool = Get-VcTool "lib.exe"

Write-Host "Reading exports from $ObsDll..."
$defFile = Join-Path $libDir "libobs.def"
$exports = & $dumpbin /exports $ObsDll | ForEach-Object {
    if ($_ -match '^\s+\d+\s+[0-9A-Fa-f]+\s+[0-9A-Fa-f]+\s+(\S+)(?:\s*=\s*(\S+))?') {
        if ($matches[2]) { $matches[2] } else { $matches[1] }
    }
} | Where-Object {
    # obs.dll also exports a couple of statically linked CRT stubs; keeping them
    # in the import library produces duplicate symbol errors when linking.
    $_ -notmatch '^(__scrt|__acrt|_CRT|_Init|_guard)'
} | Sort-Object -Unique

if (-not $exports -or $exports.Count -lt 100) {
    throw "Unexpected export table in '$ObsDll' (found $($exports.Count) exports)."
}

"LIBRARY obs.dll`nEXPORTS`n" + ($exports -join "`n") | Set-Content -Encoding ascii $defFile

Write-Host "Generating libobs.lib ($($exports.Count) exports)..."
& $libTool "/def:$defFile" /machine:x64 "/out:$(Join-Path $libDir 'libobs.lib')" | Out-Null
if ($LASTEXITCODE -ne 0) { throw "lib.exe failed." }

Copy-Item -Force $ObsDll (Join-Path $libDir "obs.dll")

Write-Host ""
Write-Host "SDK ready in $SdkDir"
Write-Host "  include/obs.h"
Write-Host "  lib/libobs.lib ($($exports.Count) symbols)"
Write-Host "  lib/obs.dll (from $ObsDll)"
